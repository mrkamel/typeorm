import "reflect-metadata"
import { expect } from "chai"
import {
    closeTestingConnections,
    createTestingConnections,
    reloadTestingDatabases,
} from "../../../utils/test-utils"
import type { DataSource } from "../../../../src/data-source/DataSource"
import { TransformedGeneratedId } from "./entity/TransformedGeneratedId"
import {
    Priority,
    TransformedDatabaseValues,
} from "./entity/TransformedDatabaseValues"
import { TransformedParent } from "./entity/TransformedParent"
import { TransformedChild } from "./entity/TransformedChild"
import { TransformedForeignKeyChild } from "./entity/TransformedForeignKeyChild"
import { TransformedTreeNode } from "./entity/TransformedTreeNode"
import { TransformedNestedSetNode } from "./entity/TransformedNestedSetNode"
import { TransformedMaterializedPathNode } from "./entity/TransformedMaterializedPathNode"

describe("columns > value-transformer > values generated by the database (#3763, #5719)", () => {
    let dataSources: DataSource[]
    before(async () => {
        dataSources = await createTestingConnections({
            entities: [
                TransformedGeneratedId,
                TransformedDatabaseValues,
                TransformedParent,
                TransformedChild,
                TransformedForeignKeyChild,
                TransformedTreeNode,
                TransformedNestedSetNode,
                TransformedMaterializedPathNode,
            ],
        })
    })
    beforeEach(() => reloadTestingDatabases(dataSources))
    after(() => closeTestingConnections(dataSources))

    const selectAll = (
        dataSource: DataSource,
        target: Function,
    ): Promise<Record<string, unknown>[]> =>
        dataSource.query(
            `SELECT * FROM ${dataSource.driver.escape(
                dataSource.getMetadata(target).tablePath,
            )}`,
        )

    const expectDatabaseValues = (
        entity: TransformedDatabaseValues,
        loaded: TransformedDatabaseValues,
        version: number,
    ) => {
        expect(entity.id).to.match(/^id:\d+$/)
        expect(entity.id).to.equal(loaded.id)
        expect(entity.hits).to.equal("hits:0")
        expect(entity.priority).to.equal(Priority.High)
        expect(entity.token).to.match(/^token:[0-9a-fA-F-]{36}$/)
        expect(entity.token).to.equal(loaded.token)
        expect(entity.version).to.equal(`version:${version}`)
        expect(loaded.version).to.equal(`version:${version}`)
    }

    it("should apply the transformer once to a generated primary key on insert", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getRepository(
                    TransformedGeneratedId,
                )
                const entity = repository.create({ title: "hello" })

                const result = await repository.insert(entity)
                const loaded = await repository.findOneByOrFail({
                    title: "hello",
                })

                expect(entity.id).to.match(/^id:\d+$/)
                expect(entity.id).to.equal(loaded.id)
                expect(result.generatedMaps[0].id).to.equal(loaded.id)
            }),
        ))

    it("should apply the transformer once to a generated primary key on save", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getRepository(
                    TransformedGeneratedId,
                )

                const entity = await repository.save(
                    repository.create({ title: "hello" }),
                )
                const loaded = await repository.findOneByOrFail({
                    id: entity.id,
                })

                expect(entity.id).to.match(/^id:\d+$/)
                expect(entity.id).to.equal(loaded.id)
            }),
        ))

    it("should apply transformers once to values filled in by the database on insert", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getRepository(
                    TransformedDatabaseValues,
                )
                const entity = repository.create({ title: "hello" })

                await repository.insert(entity)
                const loaded = await repository.findOneByOrFail({
                    title: "hello",
                })

                expectDatabaseValues(entity, loaded, 1)
            }),
        ))

    it("should apply transformers once to values filled in by the database on save", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getRepository(
                    TransformedDatabaseValues,
                )

                const entity = await repository.save(
                    repository.create({ title: "hello" }),
                )
                const loaded = await repository.findOneByOrFail({
                    id: entity.id,
                })

                expectDatabaseValues(entity, loaded, 1)
            }),
        ))

    it("should apply transformers once to values returned by an update on save", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getRepository(
                    TransformedDatabaseValues,
                )
                const entity = await repository.save(
                    repository.create({ title: "hello" }),
                )

                entity.title = "updated"
                await repository.save(entity)
                const loaded = await repository.findOneByOrFail({
                    id: entity.id,
                })

                expectDatabaseValues(entity, loaded, 2)
            }),
        ))

    it("should store the raw generated id as foreign key of cascaded children", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getRepository(TransformedParent)

                const parent = await repository.save(
                    repository.create({
                        title: "parent",
                        children: [{ title: "first" }, { title: "second" }],
                    }),
                )
                const loaded = await repository.findOneOrFail({
                    where: { id: parent.id },
                    relations: { children: true },
                })

                const children = await selectAll(dataSource, TransformedChild)

                expect(parent.id).to.match(/^id:\d+$/)
                expect(
                    loaded.children.map((child) => child.title).sort(),
                ).to.eql(["first", "second"])
                expect(children.map((child) => String(child.parentId))).to.eql([
                    parent.id.slice("id:".length),
                    parent.id.slice("id:".length),
                ])
            }),
        ))

    it("should apply the transformer of a declared foreign key column returned by an insert", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                if (!dataSource.driver.isReturningSqlSupported("insert")) return

                const parent = await dataSource
                    .getRepository(TransformedParent)
                    .save({ title: "parent" })
                const parentId = `parent:${parent.id.slice("id:".length)}`

                const result = await dataSource
                    .createQueryBuilder()
                    .insert()
                    .into(TransformedForeignKeyChild)
                    .values({ title: "child", parentId })
                    .returning(["id", "parentId"])
                    .execute()

                expect(result.generatedMaps[0].parentId).to.equal(parentId)
            }),
        ))

    it("should apply transformers once to values returned by an update with whereEntity", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getRepository(
                    TransformedDatabaseValues,
                )
                const entity = await repository.save(
                    repository.create({ title: "hello" }),
                )

                await repository
                    .createQueryBuilder()
                    .update()
                    .set({ title: "updated" })
                    .whereEntity(entity)
                    .execute()
                const loaded = await repository.findOneByOrFail({
                    id: entity.id,
                })

                expectDatabaseValues(entity, loaded, 2)
            }),
        ))

    it("should apply transformers once to values returned by soft remove and recover", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getRepository(
                    TransformedDatabaseValues,
                )
                const entity = await repository.save(
                    repository.create({ title: "hello" }),
                )

                await repository.softRemove(entity)
                const removed = await repository.findOneOrFail({
                    where: { id: entity.id },
                    withDeleted: true,
                })

                expect(entity.deletedAt).to.be.instanceOf(Date)
                expectDatabaseValues(entity, removed, 2)

                await repository.recover(entity)
                const recovered = await repository.findOneByOrFail({
                    id: entity.id,
                })

                expect(entity.deletedAt).to.equal(null)
                expectDatabaseValues(entity, recovered, 3)
            }),
        ))

    it("should store the raw generated id in the closure table", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository =
                    dataSource.getTreeRepository(TransformedTreeNode)

                const root = await repository.save(
                    repository.create({
                        title: "root",
                        children: [{ title: "child" }],
                    }),
                )
                const closureTable =
                    dataSource.getMetadata(TransformedTreeNode)
                        .closureJunctionTable.tablePath
                const closureRows: object[] = await dataSource.query(
                    `SELECT * FROM ${dataSource.driver.escape(closureTable)}`,
                )

                expect(root.id).to.match(/^id:\d+$/)
                expect(closureRows).to.have.length(3)
                for (const row of closureRows) {
                    for (const value of Object.values(row)) {
                        expect(String(value)).to.match(/^\d+$/)
                    }
                }
            }),
        ))

    it("should find the parent of cascaded nested set children", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getTreeRepository(
                    TransformedNestedSetNode,
                )
                const metadata = dataSource.getMetadata(
                    TransformedNestedSetNode,
                )

                await repository.save(
                    repository.create({
                        title: "root",
                        children: [{ title: "first" }, { title: "second" }],
                    }),
                )
                const rows = await selectAll(
                    dataSource,
                    TransformedNestedSetNode,
                )
                const bounds = Object.fromEntries(
                    rows.map((row) => [
                        row.title,
                        [
                            Number(
                                row[metadata.nestedSetLeftColumn!.databaseName],
                            ),
                            Number(
                                row[
                                    metadata.nestedSetRightColumn!.databaseName
                                ],
                            ),
                        ],
                    ]),
                )

                expect(bounds.root).to.eql([1, 6])
                expect([bounds.first, bounds.second].sort()).to.eql([
                    [2, 3],
                    [4, 5],
                ])
            }),
        ))

    it("should build the materialized path of cascaded children from entity values", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getTreeRepository(
                    TransformedMaterializedPathNode,
                )
                const pathColumn = dataSource.getMetadata(
                    TransformedMaterializedPathNode,
                ).materializedPathColumn!.databaseName

                const root = await repository.save(
                    repository.create({
                        title: "root",
                        children: [{ title: "child" }],
                    }),
                )
                const paths = Object.fromEntries(
                    (
                        await selectAll(
                            dataSource,
                            TransformedMaterializedPathNode,
                        )
                    ).map((row) => [row.title, String(row[pathColumn])]),
                )

                expect(paths.root).to.equal(`${root.id}.`)
                expect(paths.child).to.equal(
                    `${root.id}.${root.children[0].id}.`,
                )
            }),
        ))

    it("should apply transformers once to the values of every entity of a bulk insert", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                const repository = dataSource.getRepository(
                    TransformedDatabaseValues,
                )
                const entities = [
                    repository.create({ title: "first" }),
                    repository.create({ title: "second" }),
                ]

                await repository.insert(entities)

                for (const entity of entities) {
                    const loaded = await repository.findOneByOrFail({
                        title: entity.title,
                    })
                    expectDatabaseValues(entity, loaded, 1)
                }
                expect(entities[0].token).not.to.equal(entities[1].token)
            }),
        ))

    it("should apply the transformer once to a generated primary key on upsert", () =>
        Promise.all(
            dataSources.map(async (dataSource) => {
                if (dataSource.driver.supportedUpsertTypes.length === 0) return

                const repository = dataSource.getRepository(
                    TransformedGeneratedId,
                )
                const entity = repository.create({ title: "hello" })

                await repository.upsert(entity, ["title"])
                const loaded = await repository.findOneByOrFail({
                    title: "hello",
                })

                expect(entity.id).to.equal(loaded.id)
            }),
        ))
})
